/* Guest entry generated by Cranelift emit. Defined in the guest object. */
int32_t hado_entry(void);

static int print_failed;
static int process_argc;
static char **process_argv;

/* Gate instrumentation (docs/rounds/string-split-linear.md). A scan over the
   bytes of a String adds the number of bytes it looked at, so a gate can tell
   a scan from a constant-time field read. */
size_t hado_byte_scans;

/* Stack exhaustion is a run-time diagnostic, not a signal death (spec §53.1).
   The handler fires only when the fault lands near the bottom of the stack we
   recorded at startup, so a genuine bad access keeps its platform behavior. */
static char *stack_floor;
static struct sigaction previous_segv;
static struct sigaction previous_bus;
static char alternate_stack[64 * 1024];

static void write_stack_overflow(void) {
  /* No fflush(stdout) here: the fault may have happened inside a stdio call
     that already holds the stream lock, and taking it again would deadlock
     instead of reporting. Buffered stdout is lost. */
  static const char message[] = "hado: stack overflow\n";
  ssize_t written = write(STDERR_FILENO, message, sizeof(message) - 1);
  (void)written;
  _exit(1);
}

/* Hand the fault back to whoever held the signal before us (Boehm GC may have
   its own handler), and fall back to the default disposition. Masking a real
   fault behind the stack overflow line would hide the bug we want to see. */
static void chain_to_previous(int number, siginfo_t *info, void *context) {
  const struct sigaction *previous = number == SIGSEGV ? &previous_segv : &previous_bus;
  if ((previous->sa_flags & SA_SIGINFO) && previous->sa_sigaction != NULL) {
    previous->sa_sigaction(number, info, context);
    return;
  }
  if (previous->sa_handler != SIG_IGN && previous->sa_handler != SIG_DFL && previous->sa_handler != NULL) {
    previous->sa_handler(number);
    return;
  }
  signal(number, SIG_DFL);
  raise(number);
}

static void on_stack_fault(int number, siginfo_t *info, void *context) {
  uintptr_t address = (uintptr_t)info->si_addr;
  uintptr_t floor = (uintptr_t)stack_floor;
  const uintptr_t window = 1024u * 1024u;
  if (floor > window && address >= floor - window && address <= floor + window) {
    write_stack_overflow();
  }
  chain_to_previous(number, info, context);
}

static void record_stack_floor(void) {
  struct rlimit limit;
  uintptr_t top = (uintptr_t)&limit;
  uintptr_t size = 8u * 1024u * 1024u;
  if (getrlimit(RLIMIT_STACK, &limit) == 0 && limit.rlim_cur != RLIM_INFINITY) {
    size = (uintptr_t)limit.rlim_cur;
  }
  stack_floor = (char *)(top > size ? top - size : 0);
}

static void install_stack_guard(void) {
  record_stack_floor();
  stack_t alternate;
  memset(&alternate, 0, sizeof alternate);
  alternate.ss_sp = alternate_stack;
  alternate.ss_size = sizeof alternate_stack;
  if (sigaltstack(&alternate, NULL) != 0) return;
  struct sigaction action;
  memset(&action, 0, sizeof action);
  action.sa_sigaction = on_stack_fault;
  action.sa_flags = SA_SIGINFO | SA_ONSTACK;
  sigemptyset(&action.sa_mask);
  sigaction(SIGSEGV, &action, &previous_segv);
  sigaction(SIGBUS, &action, &previous_bus);
}

static void note_print_failure(void) {
  /* Why not exit() here: raise uses hado_abort_error, and main still has to
     observe a trailing fflush(stdout) failure. */
  if (print_failed) {
    return;
  }
  print_failed = 1;
  fprintf(stderr, "hado: print failed: %s\n", strerror(errno));
}

static void check_stdout(int wrote) {
  if (!wrote || ferror(stdout) || fflush(stdout) == EOF) {
    note_print_failure();
  }
}

void *hado_alloc(size_t size) { return GC_malloc(size); }

HadoArray *hado_array_alloc(int64_t count) {
  if (count < 0 || (uint64_t)count > (SIZE_MAX - 8) / 8) {
    abort();
  }
  HadoArray *array = hado_alloc(8 + 8 * (size_t)count);
  if (!array) {
    abort();
  }
  array->count = count;
  return array;
}

int64_t hado_array_length(const HadoArray *array) { return array->count; }

void hado_print_int(int64_t v) {
  check_stdout(printf("%lld\n", (long long)v) >= 0);
}

int main(int argc, char **argv) {
  process_argc = argc;
  process_argv = argv;
  signal(SIGPIPE, SIG_IGN);
  GC_INIT();
  install_stack_guard();
  int32_t code = hado_entry();
  check_stdout(1);
  return print_failed ? 1 : code;
}

static HadoString *bytes_from_c_string(const char *value) {
  size_t length = strlen(value);
  HadoString *bytes = hado_bytes_alloc((int64_t)length);
  memcpy(bytes->bytes, value, length);
  return bytes;
}

int64_t hado_argv_count(int64_t ignored) {
  /* Intrinsic applications require an argument; the dummy has no meaning. */
  (void)ignored;
  return process_argc > 0 ? process_argc - 1 : 0;
}

HadoString *hado_argv_get(int64_t index) {
  return bytes_from_c_string(process_argv[index + 1]);
}

/* Paths and env names are length-delimited and may contain NUL. Passing a
   truncated C string to fopen/getenv/opendir would operate on a different
   name (spec §55 maps that class of I/O failure to status 4). */
static char *nul_terminated_name(const HadoString *name) {
  if (memchr(name->bytes, 0, name->length) != NULL) return NULL;
  char *copy = hado_alloc(name->length + 1);
  if (copy == NULL) abort();
  memcpy(copy, name->bytes, name->length);
  copy[name->length] = 0;
  return copy;
}

int8_t hado_env_has(const HadoString *name) {
  char *c_name = nul_terminated_name(name);
  return c_name != NULL && getenv(c_name) != NULL;
}

HadoString *hado_env_get(const HadoString *name) {
  char *c_name = nul_terminated_name(name);
  const char *value = c_name == NULL ? NULL : getenv(c_name);
  return bytes_from_c_string(value == NULL ? "" : value);
}

HadoString *hado_cwd(int64_t ignored) {
  /* Intrinsic applications require an argument; the dummy has no meaning. */
  (void)ignored;
  size_t capacity = 128;
  for (;;) {
    char *buffer = hado_alloc(capacity);
    if (buffer == NULL) abort();
    if (getcwd(buffer, capacity) != NULL) return bytes_from_c_string(buffer);
    if (errno != ERANGE || capacity > SIZE_MAX / 2) return hado_bytes_alloc(0);
    capacity *= 2;
  }
}

static HadoString *io_bytes;
static HadoString **io_names;
static int64_t io_name_count;

static int64_t io_status_from_errno(int error) {
  switch (error) {
    case ENOENT: return 1;
    case EACCES: case EPERM: return 2;
    case ENOTDIR: return 3;
    default: return 4;
  }
}

static HadoString *grow_io_bytes(HadoString *bytes, size_t capacity) {
  if (capacity > INT64_MAX || capacity > SIZE_MAX - sizeof(HadoString)) abort();
  HadoString *grown = GC_realloc(bytes, sizeof(HadoString) + capacity);
  if (grown == NULL) abort();
  return grown;
}

static int64_t read_io_stream(FILE *stream) {
  size_t capacity = 8192;
  HadoString *bytes = hado_bytes_alloc((int64_t)capacity);
  bytes->length = 0;
  for (;;) {
    errno = 0;
    bytes->length += fread(bytes->bytes + bytes->length, 1, capacity - bytes->length, stream);
    if (ferror(stream)) return io_status_from_errno(errno);
    if (feof(stream)) break;
    if (capacity > SIZE_MAX / 2) abort();
    capacity *= 2;
    bytes = grow_io_bytes(bytes, capacity);
  }
  io_bytes = bytes;
  return 0;
}

int64_t hado_io_read_file(const HadoString *path) {
  io_bytes = NULL;
  char *c_path = nul_terminated_name(path);
  if (c_path == NULL) return 4;
  FILE *stream = fopen(c_path, "rb");
  if (stream == NULL) return io_status_from_errno(errno);
  int64_t status = read_io_stream(stream);
  if (fclose(stream) != 0 && status == 0) status = io_status_from_errno(errno);
  if (status != 0) io_bytes = NULL;
  return status;
}

int64_t hado_io_write_file(const HadoString *path, const HadoString *contents) {
  char *c_path = nul_terminated_name(path);
  if (c_path == NULL) return 4;
  FILE *stream = fopen(c_path, "wb");
  if (stream == NULL) return io_status_from_errno(errno);
  errno = 0;
  int64_t status = fwrite(contents->bytes, 1, contents->length, stream) == contents->length
    ? 0 : io_status_from_errno(errno);
  if (fclose(stream) != 0 && status == 0) status = io_status_from_errno(errno);
  return status;
}

int64_t hado_io_log(const HadoString *contents) {
  /* Why not io_status_from_errno: every failure of this path (EBADF, EPIPE,
     ENOSPC) is reported as the same "IoFailure", and the stream state is left
     to check_stdout so a caught failure still turns into exit 1 (spec §54). */
  int wrote = fwrite(contents->bytes, 1, contents->length, stdout) == contents->length;
  if (fputc('\n', stdout) == EOF) wrote = 0;
  if (fflush(stdout) == EOF) wrote = 0;
  return wrote ? 0 : 4;
}

int64_t hado_io_log_error(const HadoString *contents) {
  /* Same rule as hado_io_log, on stderr (§55). stderr is unbuffered by
     default, but the failure still has to be observed here: a descriptor that
     is closed or redirected to /dev/full reports it in fwrite or fflush. */
  int wrote = fwrite(contents->bytes, 1, contents->length, stderr) == contents->length;
  if (fputc('\n', stderr) == EOF) wrote = 0;
  if (fflush(stderr) == EOF) wrote = 0;
  return wrote ? 0 : 4;
}

/* §54: an Int main outside 0..=255 is diagnosed before it is narrowed to the
   ABI's i32, so the OS never normalizes a negative value or 256. write(2) is
   used because stderr's stream state is not this function's to trust. */
void hado_exit_code_out_of_range(void) {
  static const char message[] = "hado: exit code out of range\n";
  ssize_t written = write(STDERR_FILENO, message, sizeof(message) - 1);
  (void)written;
}

int64_t hado_io_read_stdin(int64_t ignored) {
  /* Intrinsic applications require a dummy argument; stdin is the only input. */
  (void)ignored;
  io_bytes = NULL;
  if (fcntl(STDIN_FILENO, F_GETFD) == -1 && errno == EBADF) {
    io_bytes = hado_bytes_alloc(0);
    return 0;
  }
  return read_io_stream(stdin);
}

HadoString *hado_io_take_bytes(int64_t ignored) {
  /* Only a successful read may consume the payload; the dummy is unused. */
  (void)ignored;
  HadoString *bytes = io_bytes;
  if (bytes == NULL) abort();
  io_bytes = NULL;
  return bytes;
}

static void append_io_name(const char *name, size_t *capacity) {
  if ((size_t)io_name_count == *capacity) {
    if (*capacity > SIZE_MAX / 2 / sizeof(HadoString *)) abort();
    *capacity = *capacity == 0 ? 16 : *capacity * 2;
    io_names = GC_realloc(io_names, *capacity * sizeof(HadoString *));
    if (io_names == NULL) abort();
  }
  io_names[io_name_count++] = bytes_from_c_string(name);
}

static int compare_io_names(const void *left, const void *right) {
  return (int)hado_string_compare(*(HadoString *const *)left, *(HadoString *const *)right);
}

static int64_t collect_io_names(DIR *directory) {
  size_t capacity = 0;
  for (;;) {
    errno = 0;
    struct dirent *entry = readdir(directory);
    if (entry == NULL) return errno == 0 ? 0 : io_status_from_errno(errno);
    if (strcmp(entry->d_name, ".") == 0 || strcmp(entry->d_name, "..") == 0) continue;
    append_io_name(entry->d_name, &capacity);
  }
}

int64_t hado_io_read_dir(const HadoString *path) {
  io_names = NULL;
  io_name_count = 0;
  char *c_path = nul_terminated_name(path);
  if (c_path == NULL) return 4;
  DIR *directory = opendir(c_path);
  if (directory == NULL) return io_status_from_errno(errno);
  int64_t status = collect_io_names(directory);
  if (closedir(directory) != 0 && status == 0) status = io_status_from_errno(errno);
  if (status != 0) {
    io_names = NULL;
    io_name_count = 0;
    return status;
  }
  if (io_name_count > 1) qsort(io_names, (size_t)io_name_count, sizeof(HadoString *), compare_io_names);
  return 0;
}

int64_t hado_io_dir_count(int64_t ignored) {
  /* Intrinsic applications require an argument; the dummy has no meaning. */
  (void)ignored;
  return io_name_count;
}

HadoString *hado_io_dir_get(int64_t index) { return io_names[index]; }

size_t hado_scalar_count(const unsigned char *bytes, size_t length) {
  hado_byte_scans += length;
  size_t count = 0;
  for (size_t i = 0; i < length; ++i) {
    if ((bytes[i] & 0xc0) != 0x80) {
      if (count == SIZE_MAX) abort();
      ++count;
    }
  }
  return count;
}

int64_t hado_string_length(const HadoString *string) {
  if (string->scalars != HADO_SCALARS_UNKNOWN) return (int64_t)string->scalars;
  /* Reaching here means a String was built without its scalar count. Fall
     back to a scan so the value stays correct rather than reporting the
     marker; every String-producing path is expected to have filled it. */
  return (int64_t)hado_scalar_count(string->bytes, string->length);
}

HadoString *hado_string_concat(const HadoString *left, const HadoString *right) {
  if (left->length > SIZE_MAX - right->length) abort();
  size_t length = left->length + right->length;
  if (length > SIZE_MAX - sizeof(HadoString)) abort();
  if (left->scalars > SIZE_MAX - right->scalars) abort();
  HadoString *result = hado_alloc(sizeof(HadoString) + length);
  if (result == NULL) abort();
  result->length = length;
  result->scalars = left->scalars + right->scalars;
  memcpy(result->bytes, left->bytes, left->length);
  memcpy(result->bytes + left->length, right->bytes, right->length);
  return result;
}

int64_t hado_string_compare(const HadoString *left, const HadoString *right) {
  size_t common = left->length < right->length ? left->length : right->length;
  int order = memcmp(left->bytes, right->bytes, common);
  if (order != 0) return order < 0 ? -1 : 1;
  return (left->length > right->length) - (left->length < right->length);
}

static size_t string_byte_offset(const HadoString *string, int64_t index) {
  size_t offset = 0;
  while (index > 0) {
    ++offset;
    while (offset < string->length && (string->bytes[offset] & 0xc0) == 0x80) {
      ++offset;
    }
    --index;
  }
  hado_byte_scans += offset;
  return offset;
}

static size_t scalars_between(const unsigned char *bytes, size_t start, size_t end) {
  hado_byte_scans += end - start;
  size_t count = 0;
  for (size_t i = start; i < end; ++i) {
    if ((bytes[i] & 0xc0) != 0x80) ++count;
  }
  return count;
}

HadoString *hado_string_slice(const HadoString *string, int64_t start, int64_t end) {
  size_t first = string_byte_offset(string, start);
  size_t length = string_byte_offset(string, end) - first;
  if (length > SIZE_MAX - sizeof(HadoString)) abort();
  if (end < start) abort();
  HadoString *result = hado_alloc(sizeof(HadoString) + length);
  if (result == NULL) abort();
  result->length = length;
  result->scalars = (size_t)(end - start);
  memcpy(result->bytes, string->bytes + first, length);
  return result;
}

uint32_t hado_string_get(const HadoString *string, int64_t index) {
  size_t offset = string_byte_offset(string, index);
  uint32_t scalar = string->bytes[offset++];
  if (scalar < 0x80) return scalar;
  scalar &= scalar < 0xe0 ? 0x1f : scalar < 0xf0 ? 0x0f : 0x07;
  while (offset < string->length && (string->bytes[offset] & 0xc0) == 0x80) {
    scalar = (scalar << 6) | (string->bytes[offset++] & 0x3f);
  }
  return scalar;
}

int64_t hado_string_find(const HadoString *string, const HadoString *separator, int64_t from) {
  size_t offset = string_byte_offset(string, from);
  for (; offset < string->length; ++offset) {
    if ((string->bytes[offset] & 0xc0) == 0x80) continue;
    if (separator->length > string->length - offset) return -1;
    if (memcmp(string->bytes + offset, separator->bytes, separator->length) == 0) return from;
    ++from;
  }
  return -1;
}

static HadoString *make_piece(const HadoString *string, size_t start, size_t end) {
  size_t length = end - start;
  if (length > SIZE_MAX - sizeof(HadoString)) abort();
  HadoString *piece = hado_alloc(sizeof(HadoString) + length);
  if (piece == NULL) abort();
  piece->length = length;
  piece->scalars = hado_scalar_count(string->bytes + start, length);
  memcpy(piece->bytes, string->bytes + start, length);
  return piece;
}

/* Splits on non-overlapping occurrences of `separator`, which the prelude has
   already checked to be non-empty (spec §55 maps the empty case to
   EmptySeparator). memmem is linear in the input length, so a separator whose
   length grows with the input cannot turn the scan quadratic; a candidate-by-
   candidate memcmp loop can (docs/rounds/string-split-linear.md). Every piece
   carries its scalar count, so String.length of a piece never scans. */
HadoString *hado_string_split(const HadoString *string, const HadoString *separator) {
  size_t width = separator->length;
  if (width == 0) abort();
  size_t pieces = 1;
  size_t position = 0;
  while (position + width <= string->length) {
    const unsigned char *found = memmem(string->bytes + position, string->length - position,
                                        separator->bytes, width);
    if (found == NULL) break;
    ++pieces;
    position = (size_t)(found - string->bytes) + width;
  }
  HadoArray *array = hado_array_alloc((int64_t)pieces);
  size_t index = 0;
  size_t start = 0;
  position = 0;
  while (position + width <= string->length) {
    const unsigned char *found = memmem(string->bytes + position, string->length - position,
                                        separator->bytes, width);
    if (found == NULL) break;
    size_t end = (size_t)(found - string->bytes);
    array->slots[index++] = (uint64_t)(uintptr_t)make_piece(string, start, end);
    start = end + width;
    position = start;
  }
  array->slots[index++] = (uint64_t)(uintptr_t)make_piece(string, start, string->length);
  return (HadoString *)array;
}

/* Joins with the separator between elements only (spec §55): no separator for
   an empty or single-element list. The output length is summed first and the
   bytes are copied once, so the cost is linear in the total length. */
HadoString *hado_string_join(const HadoArray *values, const HadoString *separator) {
  int64_t count = values->count;
  if (count <= 0) {
    HadoString *empty = hado_alloc(sizeof(HadoString));
    if (empty == NULL) abort();
    empty->length = 0;
    empty->scalars = 0;
    return empty;
  }
  size_t total = 0;
  size_t scalars = 0;
  for (int64_t i = 0; i < count; ++i) {
    const HadoString *value = (const HadoString *)(uintptr_t)values->slots[i];
    if (value->length > SIZE_MAX - total) abort();
    total += value->length;
    if (value->scalars == HADO_SCALARS_UNKNOWN) {
      scalars += hado_scalar_count(value->bytes, value->length);
    } else {
      if (value->scalars > SIZE_MAX - scalars) abort();
      scalars += value->scalars;
    }
  }
  if (separator->length > 0) {
    size_t separators = (size_t)(count - 1);
    if (separators > SIZE_MAX / separator->length) abort();
    size_t extra = separators * separator->length;
    if (extra > SIZE_MAX - total) abort();
    total += extra;
    if (separator->scalars > SIZE_MAX - scalars) abort();
    if (separators > (SIZE_MAX - scalars) / separator->scalars) abort();
    scalars += separators * separator->scalars;
  }
  if (total > SIZE_MAX - sizeof(HadoString)) abort();
  HadoString *result = hado_alloc(sizeof(HadoString) + total);
  if (result == NULL) abort();
  result->length = total;
  result->scalars = scalars;
  size_t offset = 0;
  for (int64_t i = 0; i < count; ++i) {
    const HadoString *value = (const HadoString *)(uintptr_t)values->slots[i];
    if (i > 0) {
      memcpy(result->bytes + offset, separator->bytes, separator->length);
      offset += separator->length;
    }
    memcpy(result->bytes + offset, value->bytes, value->length);
    offset += value->length;
  }
  return result;
}

static int is_ascii_space(unsigned char byte) {
  return byte == '\t' || byte == '\n' || byte == '\v' || byte == '\f' || byte == '\r' || byte == ' ';
}

HadoString *hado_string_trim(const HadoString *string) {
  /* Bytes may be trimmed here: the six whitespace bytes are ASCII, and every
     continuation byte of UTF-8 is at least 0x80, so no scalar is split. */
  size_t first = 0;
  size_t last = string->length;
  while (first < last && is_ascii_space(string->bytes[first])) ++first;
  while (last > first && is_ascii_space(string->bytes[last - 1])) --last;
  size_t length = last - first;
  if (length > SIZE_MAX - sizeof(HadoString)) abort();
  HadoString *result = hado_alloc(sizeof(HadoString) + length);
  if (result == NULL) abort();
  result->length = length;
  result->scalars = scalars_between(string->bytes, first, last);
  memcpy(result->bytes, string->bytes + first, length);
  return result;
}

void hado_print_string(const HadoString *string) {
  int wrote = fwrite(string->bytes, 1, string->length, stdout) == string->length
              && fputc('\n', stdout) != EOF;
  check_stdout(wrote);
}

static size_t encode_char(uint32_t value, unsigned char bytes[4]) {
  size_t length;
  if (value <= 0x7f) {
    bytes[0] = value;
    length = 1;
  } else if (value <= 0x7ff) {
    bytes[0] = 0xc0 | (value >> 6);
    bytes[1] = 0x80 | (value & 0x3f);
    length = 2;
  } else if (value <= 0xffff && !(value >= 0xd800 && value <= 0xdfff)) {
    bytes[0] = 0xe0 | (value >> 12);
    bytes[1] = 0x80 | ((value >> 6) & 0x3f);
    bytes[2] = 0x80 | (value & 0x3f);
    length = 3;
  } else if (value >= 0x10000 && value <= 0x10ffff) {
    bytes[0] = 0xf0 | (value >> 18);
    bytes[1] = 0x80 | ((value >> 12) & 0x3f);
    bytes[2] = 0x80 | ((value >> 6) & 0x3f);
    bytes[3] = 0x80 | (value & 0x3f);
    length = 4;
  } else {
    abort();
  }
  return length;
}

void hado_print_char(uint32_t value) {
  unsigned char bytes[4];
  size_t length = encode_char(value, bytes);
  int wrote = fwrite(bytes, 1, length, stdout) == length && fputc('\n', stdout) != EOF;
  check_stdout(wrote);
}

void hado_print_float(double value) {
  check_stdout(printf("%.17g\n", value) >= 0);
}

HadoString *hado_int_to_string(int64_t value) {
  char buffer[32];
  int length = snprintf(buffer, sizeof(buffer), "%lld", (long long)value);
  if (length < 0 || (size_t)length >= sizeof(buffer)) abort();
  HadoString *result = hado_alloc(sizeof(HadoString) + (size_t)length);
  if (result == NULL) abort();
  result->length = (size_t)length;
  result->scalars = (size_t)length;
  memcpy(result->bytes, buffer, result->length);
  return result;
}

typedef struct {
  int8_t valid;
  int64_t value;
} IntParseResult;

static IntParseResult parse_int_digits(const HadoString *string, size_t index) {
  while (index < string->length && string->bytes[index] == '0') ++index;
  int64_t acc = 0;
  for (; index < string->length; ++index) {
    int64_t digit = (int64_t)string->bytes[index] - '0';
    if (digit < 0 || digit > 9) return (IntParseResult){0, 0};
    if (acc < (INT64_MIN + digit) / 10) return (IntParseResult){0, 0};
    acc = acc * 10 - digit;
  }
  return (IntParseResult){1, acc};
}

static IntParseResult parse_int(const HadoString *string) {
  if (string->length == 0) return (IntParseResult){0, 0};
  int negative = string->bytes[0] == '-';
  size_t start = (size_t)negative;
  if (start == string->length) return (IntParseResult){0, 0};
  IntParseResult result = parse_int_digits(string, start);
  if (!negative && result.value == INT64_MIN) return (IntParseResult){0, 0};
  result.value = negative ? result.value : -result.value;
  return result;
}

int8_t hado_int_parse_is_valid(const HadoString *string) {
  return parse_int(string).valid;
}

int64_t hado_int_parse_unchecked(const HadoString *string) {
  return parse_int(string).value;
}

/* §55: the accepted spelling is exactly `"-"? digit+ "." digit+`: the whole
   string must match, `+` and exponents are not accepted, and leading zeros
   and trailing fraction zeros are. */
static int float_grammar(const HadoString *string) {
  size_t index = 0;
  if (string->length == 0) return 0;
  if (string->bytes[0] == '-') index = 1;
  size_t integer_start = index;
  while (index < string->length && string->bytes[index] >= '0' && string->bytes[index] <= '9') {
    ++index;
  }
  if (index == integer_start) return 0;
  if (index >= string->length || string->bytes[index] != '.') return 0;
  ++index;
  size_t fraction_start = index;
  while (index < string->length && string->bytes[index] >= '0' && string->bytes[index] <= '9') {
    ++index;
  }
  if (index == fraction_start) return 0;
  return index == string->length;
}

static int float_has_nonzero_digit(const HadoString *string) {
  for (size_t index = 0; index < string->length; ++index) {
    if (string->bytes[index] >= '1' && string->bytes[index] <= '9') return 1;
  }
  return 0;
}

/* strtod rounds to nearest with ties to even on glibc. The copy only exists to
   NUL-terminate the bytes: the grammar check already fixed the shape. */
static double float_parse_bytes(const HadoString *string) {
  if (string->length == SIZE_MAX) abort();
  char *buffer = hado_alloc(string->length + 1);
  if (buffer == NULL) abort();
  memcpy(buffer, string->bytes, string->length);
  buffer[string->length] = '\0';
  return strtod(buffer, NULL);
}

int8_t hado_float_parse_is_valid(const HadoString *string) {
  if (!float_grammar(string)) return 0;
  double value = float_parse_bytes(string);
  /* A spelling that rounds to infinity overflows, and a spelling with a
     nonzero digit that rounds to zero underflows: neither is a Float. A
     nonzero subnormal is accepted, so ERANGE alone is not the test. */
  if (isinf(value)) return 0;
  if (value == 0.0 && float_has_nonzero_digit(string)) return 0;
  return 1;
}

double hado_float_parse_unchecked(const HadoString *string) {
  return float_parse_bytes(string);
}

/* §54: the same canonical spelling the printer uses, from the Rust formatter.
   Keeping one formatter keeps `Float.to_string x` and the print of `x` equal. */
HadoString *hado_float_to_string(double value) {
  unsigned char bytes[400];
  size_t length = hado_format_float(value, bytes, sizeof(bytes));
  if (length == 0 || length > sizeof(bytes)) abort();
  HadoString *result = hado_alloc(sizeof(HadoString) + length);
  if (result == NULL) abort();
  result->length = length;
  result->scalars = length;
  memcpy(result->bytes, bytes, length);
  return result;
}

